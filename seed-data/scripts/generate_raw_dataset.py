QUOTE_RE = re.compile(r'["«»“”](.+?)["«»“”]')
TOKEN_RE = re.compile(r"[^\W_]+", re.UNICODE)


def collapse_spaces(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def canonicalize(raw: str) -> str:
    value = unicodedata.normalize("NFKC", raw.strip()).lower()
    return value.replace("ё", "е")


def normalized_name(raw: str) -> str:
    prepared = canonicalize(raw)
    phrases: list[str] = []

    def repl(match: re.Match[str]) -> str:
        phrase = collapse_spaces(match.group(1))
        if phrase:
            phrases.append(phrase)
        return " "

    without_quotes = QUOTE_RE.sub(repl, prepared)
    words: list[str] = []
    seen: set[str] = set()
    for token in TOKEN_RE.findall(without_quotes):
        if token in STOP_WORDS or token in seen:
            continue
        seen.add(token)
        words.append(token)

    phrase_queue = list(phrases)
    rebuilt = QUOTE_RE.sub(
        lambda match: (
            " "
            if not collapse_spaces(match.group(1))
            else f'"{phrase_queue.pop(0) if phrase_queue else collapse_spaces(match.group(1))}"'
        ),
        prepared,
    )
    leftover = [t for t in TOKEN_RE.findall(QUOTE_RE.sub(" ", rebuilt)) if t not in STOP_WORDS]
    phrase_tokens = [m.group(0).strip() for m in QUOTE_RE.finditer(rebuilt)]
    result = collapse_spaces(" ".join(leftover + phrase_tokens))
    if result:
        return result
    return words[0] if words else (phrases[0] if phrases else "")


def n_with_location(n_rows: int, category: str) -> int:
    return round(n_rows * LOCATION_RATE[category])


def assign_locations(
    rows: list[tuple[str, str]],
    fixed: dict[tuple[str, str], str],
    supermarket_slots: int,
) -> list[tuple[str, str, str]]:
    by_category: dict[str, list[str]] = {code: [] for code in CATEGORIES}
    for name, category in rows:
        by_category[category].append(name)

    out: list[tuple[str, str, str]] = []
    loc_index = {code: 0 for code in CATEGORIES}
    amb_index = 0

    for category, names in by_category.items():
        target_filled = n_with_location(len(names), category)
        assigned: dict[str, str | None] = {name: None for name in names}
        for name in names:
            key = (name, category)
            if key in fixed:
                assigned[name] = fixed[key]

        filled = sum(1 for loc in assigned.values() if loc)
        empty = sum(1 for loc in assigned.values() if loc == "")
        unassigned = [name for name, loc in assigned.items() if loc is None]
        need_filled = max(0, target_filled - filled)
        need_empty = max(0, len(names) - target_filled - empty)

        supermarket_left = supermarket_slots if category in {"HEALTH", "HOME", "GROCERIES"} else 0
        if category == "GROCERIES":
            supermarket_left = 0

        for name in unassigned:
            if need_filled > 0:
                if supermarket_left > 0 and category in {"HEALTH", "HOME"}:
                    assigned[name] = AMBIGUOUS_STORES[amb_index % len(AMBIGUOUS_STORES)]
                    amb_index += 1
                    supermarket_left -= 1
                else:
                    pool = LOCATIONS[category]
                    assigned[name] = pool[loc_index[category] % len(pool)]
                    loc_index[category] += 1
                need_filled -= 1
            elif need_empty > 0:
                assigned[name] = ""
                need_empty -= 1
            else:
                assigned[name] = ""

        for name in names:
            location = assigned[name]
            assert location is not None
            out.append((name, location, category))
    return out


def split_names() -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    train: list[tuple[str, str]] = []
    val: list[tuple[str, str]] = []
    golden_names = {name for name, _, _ in GOLDEN_TRAIN}
    val_fixed_names = {name for name, _, _ in FIXED_VAL}

    for category, names in NAMES.items():
        if len(names) != 100:
            raise SystemExit(f"{category}: ожидалось 100 имён, получено {len(names)}")
        if len(set(names)) != 100:
            dupes = [name for name, count in Counter(names).items() if count > 1]
            raise SystemExit(f"{category}: дубли имён: {dupes}")

        train_fixed = [name for name, _, code in GOLDEN_TRAIN if code == category]
        val_fixed = [name for name, _, code in FIXED_VAL if code == category]
        remaining = [name for name in names if name not in set(train_fixed + val_fixed)]
        need_train = TRAIN_PER_CATEGORY - len(train_fixed)
        need_val = VAL_PER_CATEGORY - len(val_fixed)
        train_names = train_fixed + remaining[:need_train]
        val_names = val_fixed + remaining[need_train : need_train + need_val]
        if len(train_names) != TRAIN_PER_CATEGORY or len(val_names) != VAL_PER_CATEGORY:
            raise SystemExit(
                f"{category}: split {len(train_names)}/{len(val_names)}, "
                f"fixed train={train_fixed} val={val_fixed}"
            )
        missing_golden = [name for name in train_fixed if name not in names and name not in golden_names]
        if missing_golden:
            raise SystemExit(f"{category}: golden нет в каталоге: {missing_golden}")
        for name in train_fixed:
            if name not in names:
                raise SystemExit(f"{category}: golden «{name}» нет в NAMES")
        for name in val_fixed:
            if name not in names:
                raise SystemExit(f"{category}: validation fixed «{name}» нет в NAMES")
        train.extend((name, category) for name in train_names)
        val.extend((name, category) for name in val_names)

    leftover_golden = golden_names - {name for name, _ in train}
    leftover_val = val_fixed_names - {name for name, _ in val}
    if leftover_golden:
        raise SystemExit(f"golden не попали в train: {leftover_golden}")
    if leftover_val:
        raise SystemExit(f"fixed val не попали в validation: {leftover_val}")
    return train, val


def write_csv(path: Path, rows: list[tuple[str, str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["name", "location", "category_code"])
        writer.writerows(rows)


def validate(train: list[tuple[str, str, str]], val: list[tuple[str, str, str]]) -> None:
    if len(train) != 800:
        raise SystemExit(f"train: {len(train)} строк, ожидалось 800")
    if len(val) != 200:
        raise SystemExit(f"validation: {len(val)} строк, ожидалось 200")

    train_counts = Counter(category for _, _, category in train)
    val_counts = Counter(category for _, _, category in val)
    for category in CATEGORIES:
        if train_counts[category] != 80:
            raise SystemExit(f"train {category}: {train_counts[category]}")
        if val_counts[category] != 20:
            raise SystemExit(f"validation {category}: {val_counts[category]}")

    train_norm = [normalized_name(name) for name, _, _ in train]
    val_norm = [normalized_name(name) for name, _, _ in val]
    if "" in train_norm or "" in val_norm:
        raise SystemExit("пустой normalized_name")
    if len(set(train_norm)) != len(train_norm):
        dupes = [name for name, count in Counter(train_norm).items() if count > 1]
        raise SystemExit(f"train: коллизии normalized_name: {dupes}")
    if len(set(val_norm)) != len(val_norm):
        dupes = [name for name, count in Counter(val_norm).items() if count > 1]
        raise SystemExit(f"validation: коллизии normalized_name: {dupes}")
    overlap = set(train_norm) & set(val_norm)
    if overlap:
        raise SystemExit(f"пересечение train/validation: {sorted(overlap)}")

    for name, location, category in GOLDEN_TRAIN:
        if (name, location, category) not in train:
            raise SystemExit(f"нет golden в train: {name!r}, {location!r}, {category}")
    for name, location, category in FIXED_VAL:
        if (name, location, category) not in val:
            raise SystemExit(f"нет edge-case в validation: {name!r}, {location!r}, {category}")

    print("location fill rates:")
    for split_name, rows in ("train", train), ("validation", val):
        print(f"  {split_name}")
        for category in CATEGORIES:
            subset = [loc for name, loc, code in rows if code == category]
            filled = sum(1 for loc in subset if loc)
            target = n_with_location(len(subset), category)
            print(f"    {category}: {filled}/{len(subset)} (цель {target})")


def assert_catalog_unique() -> None:
    by_norm: dict[str, list[tuple[str, str]]] = {}
    for category, names in NAMES.items():
        for name in names:
            key = normalized_name(name)
            by_norm.setdefault(key, []).append((category, name))
    collisions = {key: items for key, items in by_norm.items() if len(items) > 1}
    if collisions:
        raise SystemExit(f"коллизии в каталоге: {collisions}")


def main() -> None:
    assert_catalog_unique()
    train_pairs, val_pairs = split_names()
    golden_fixed = {(name, category): location for name, location, category in GOLDEN_TRAIN}
    val_fixed = {(name, category): location for name, location, category in FIXED_VAL}
    train_rows = assign_locations(train_pairs, golden_fixed, supermarket_slots=4)
    val_rows = assign_locations(val_pairs, val_fixed, supermarket_slots=0)
    validate(train_rows, val_rows)
    write_csv(TRAIN_PATH, train_rows)
    write_csv(VAL_PATH, val_rows)
    print(f"wrote {TRAIN_PATH} ({len(train_rows)} rows)")
    print(f"wrote {VAL_PATH} ({len(val_rows)} rows)")


if __name__ == "__main__":
    main()
